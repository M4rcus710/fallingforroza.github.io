// Builds the website from content/*.json into plain HTML files.
//
//   npm run build                     writes the site into this folder (what GitHub Pages serves)
//   node src/build.js --out <dir>     writes it somewhere else instead (assets are copied along)
//   node src/build.js --gigs <file>   uses another list of shows instead of content/gigs.json (for tests)
//   TODAY=2026-11-15 npm run build    pretends it's another day (to check past/upcoming)

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { today } from '../assets/js/lib/dates.js';
import { loadContent } from './lib/content.js';
import { layout } from './templates/layout.js';
import { jsonLdScript, lastDay } from './templates/parts.js';
import { homePage } from './pages/home.js';
import { nightPage, calendarFile } from './pages/night.js';
import { upcomingPage } from './pages/upcoming.js';
import { aboutPage } from './pages/about.js';
import { musicPage } from './pages/music.js';
import { shopPage } from './pages/shop.js';
import { imprintPage } from './pages/imprint.js';
import { privacyPage } from './pages/privacy.js';
import { notFoundPage, legacyRedirects, redirectPage, sitemap, robots } from './pages/extras.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GENERATED_NOTE = '<!-- Generated by `npm run build` from content/ and src/. Edit those, not this file. -->';

// Shows that existed on the old Framer site; their old …/page.html addresses keep working.
const FRAMER_IDS = ['backstage-club', 'quax', 'penzberg', 'strom', 'backstage-halle', 'sommernaechte'];

function option(name) {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : null;
}

function assetVersion(root) {
  const hash = crypto.createHash('sha256');
  for (const dir of ['assets/css', 'assets/js', 'assets/js/lib']) {
    for (const file of fs.readdirSync(path.join(root, dir)).sort()) {
      const full = path.join(root, dir, file);
      if (fs.statSync(full).isFile()) hash.update(fs.readFileSync(full));
    }
  }
  return hash.digest('hex').slice(0, 10);
}

export function build({ root = ROOT, gigsFile, out = root, todayIso = process.env.TODAY || today() } = {}) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(todayIso)) throw new Error(`TODAY must look like 2026-11-15, not "${todayIso}"`);
  const content = loadContent(root, { todayIso, gigsFile });
  const { site, gigs, past, upcoming, warnings } = content;
  for (const w of warnings) console.warn(`warning: ${w}`);

  const ctx = {
    ...content,
    root,
    todayIso,
    year: todayIso.slice(0, 4),
    assetVersion: assetVersion(root),
    upcomingDates: upcoming.map(lastDay),
  };

  const written = [];
  const write = (relative, text) => {
    const file = path.join(out, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    written.push(relative);
  };
  const page = (relative, model) =>
    write(relative, layout(model, ctx).replace('<!doctype html>', `<!doctype html>\n${GENERATED_NOTE}`));

  if (out !== root) {
    fs.rmSync(path.join(out, 'assets'), { recursive: true, force: true });
    fs.cpSync(path.join(root, 'assets'), path.join(out, 'assets'), { recursive: true });
  }
  // live/ is completely generated, so shows removed from gigs.json disappear too.
  fs.rmSync(path.join(out, 'live'), { recursive: true, force: true });

  const home = homePage(ctx);
  home.head = jsonLdScript({
    '@type': 'MusicGroup',
    name: site.name,
    url: site.url,
    description: site.description,
    genre: 'Rock',
    foundingLocation: { '@type': 'Place', name: 'Munich' },
    email: site.email,
    sameAs: site.socials.map((s) => s.url),
  });
  page('index.html', home);
  page('upcoming/index.html', upcomingPage(ctx));
  page('about/index.html', aboutPage(ctx));
  page('music/index.html', musicPage(ctx));
  page('shop/index.html', shopPage(ctx));
  page('imprint/index.html', imprintPage(ctx));
  page('privacy/index.html', privacyPage(ctx));
  page('404.html', notFoundPage(ctx));
  for (const gig of gigs) {
    page(`live/${gig.id}/index.html`, nightPage(gig, ctx));
    if (gig.isUpcoming && gig.parsedDate.precision === 'day') write(`live/${gig.id}/calendar.ics`, calendarFile(gig, site, todayIso));
  }

  const keep = FRAMER_IDS.filter((id) => gigs.some((g) => g.id === id));
  for (const [from, to] of Object.entries(legacyRedirects(keep))) write(from, redirectPage(to, site.url));

  const pages = ['/', '/upcoming/', '/music/', '/shop/', '/about/', ...gigs.map((g) => g.url), '/imprint/', '/privacy/'];
  write('sitemap.xml', sitemap(pages, site.url));
  write('robots.txt', robots(site.url));

  return { written, past: past.length, upcoming: upcoming.length, todayIso, warnings };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const gigsFile = option('gigs');
    const outDir = option('out');
    const result = build({
      gigsFile: gigsFile ? path.resolve(gigsFile) : undefined,
      out: outDir ? path.resolve(outDir) : ROOT,
    });
    console.log(
      `Built ${result.written.length} files for ${result.todayIso}: ` +
        `${result.past} past show(s), ${result.upcoming} upcoming.`,
    );
  } catch (error) {
    console.error(`\nBuild failed.\n\n${error.message}\n`);
    process.exit(1);
  }
}
